static u8 s_Line[128];

static void Text(u8 page, u8 y, const char* text)
{
    u8 row, offset=0, length=0, character, i;
    u8* destination;
    const u8* source;
    while (length<37 && text[length]) ++length;
    for (row=0; row<7; ++row)
    {
        destination=s_Line;
        for (i=0; i<length; ++i)
        {
            character=text[i];
            if (character>='A' && character<='Z') character-='A';
            else if (character>='0' && character<='9') character=26+character-'0';
            else character=character=='>' ? 36 : 37;
            source=s_Font[character]+offset;
            *destination++=*source++;
            *destination++=*source++;
            *destination++=*source;
        }
        VDP_WriteVRAM(s_Line,((u16)page*256+y+row)*128+12,0,length*3);
        offset+=3;
    }
}

void Menu_Draw(u8 page, const GameState* game) WINGS_BANKED
{
    u8 i;
    char rank[]="  RANK 1";
    VDP_CommandHMMV(0,(u16)page*256,256,172,0x11);
    VDP_CommandWait();
    Text(page,12,"WINGS OF FURY");
    if (game->phase==GAME_RANK)
    {
        Text(page,30,"SELECT RANK");
        for (i=0; i<7; ++i)
        {
            rank[0]=game->cursor==i ? '>' : ' ';
            rank[7]='1'+i; Text(page,48+i*11,rank);
        }
        Text(page,125,game->cursor==7 ? "> RETURN FROM R AND R" : "  RETURN FROM R AND R");
        Text(page,151,"ARROWS TO CHOOSE  ENTER TO CONFIRM");
    }
    else if (game->phase==GAME_BRIEFING)
    {
        Text(page,42,"MISSION A");
        Text(page,65,"PRACTICE SORTIE");
        Text(page,88,"NO MISSION OBJECTIVES");
        Text(page,145,"ENTER OR BUTTON TO CONTINUE");
    }
    else if (game->phase==GAME_LOADOUT || game->phase==GAME_SERVICE)
    {
        Text(page,38,game->phase==GAME_SERVICE ? "HOLD  REARM AND REFUEL" : "SELECT LOADOUT");
        Text(page,62,game->cursor==0 ? "> BOMBS 30" : "  BOMBS 30");
        Text(page,80,game->cursor==1 ? "> ROCKETS 15" : "  ROCKETS 15");
        Text(page,98,game->cursor==2 ? "> TORPEDO 1" : "  TORPEDO 1");
        if (game->cursor || game->notice) Text(page,122,"NOT AVAILABLE IN THIS BUILD");
        Text(page,151,"ENTER OR BUTTON TO CONFIRM");
    }
    else if (game->phase==GAME_OVER)
    {
        Text(page,65,"GAME OVER"); Text(page,100,"ENTER OR BUTTON TO CONTINUE");
    }
    else if (game->phase==GAME_PAUSE)
    {
        Text(page,65,"PAUSED"); Text(page,100,"PRESS ESC TO CONTINUE");
    }
    else
    {
        Text(page,54,game->phase==GAME_SAVE_MENU ? "SAVE GAME" : "LOAD GAME");
        Text(page,84,"NOT AVAILABLE IN THIS BUILD");
        Text(page,128,"ENTER OR BUTTON TO RETURN");
    }
    VDP_CommandWait();
}
