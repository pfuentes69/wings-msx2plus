#!/usr/bin/env python3
"""The FM engine's pitch table (src/generated/fm_pitch.h, src/msx/sound_fm.c).

The engine drones at the PSG version's pitch, 49,956 / P Hz for the
original's Paula period P (docs/sound-effects.md). On the YM2413 in block 2
that is fnum = 131,700 / P. A table indexed by P / 2 replaces the divisions,
which cost about a millisecond a frame in SDCC's C. --check verifies the
generated file."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/generated/fm_pitch.h'
FIRST, COUNT = 128, 512        # P / 2 = 128..639: P 256..1279


def render():
    values = [min(511, round(131700 / (2 * half + 1))) for half in range(FIRST, FIRST + COUNT)]
    rows = [', '.join(str(v) for v in values[i:i + 16]) for i in range(0, COUNT, 16)]
    body = ',\n    '.join(rows)
    return (f'/* Generated by tools/convert_fm_pitch.py; do not edit. */\n#pragma once\n'
            f'#define FM_PITCH_FIRST {FIRST}   /* P / 2 of the first entry */\n'
            f'#define FM_PITCH_COUNT {COUNT}\n'
            f'/* The engine\'s fnum in block 2 for period P: s_FMPitch[P / 2 - FM_PITCH_FIRST]. */\n'
            f'static const unsigned short s_FMPitch[FM_PITCH_COUNT] = {{\n    {body}}};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = render()
    if args.check:
        if OUTPUT.read_text() != text: raise SystemExit(f'{OUTPUT} is out of date')
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
