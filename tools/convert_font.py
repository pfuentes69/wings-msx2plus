"""Convert the original's ticker font (newarmyfont) and its island/mission
messages (from the wings executable) for the MSX message ticker.

newarmyfont: u16 height (12), u8 first (0x20), u8 last (0x7e), then a width
byte per character from the first, then each glyph from first + 1 as 12
rows of 16 bits (32 bits when wider than 16 px), most significant bit left.
The space has no bitmap.

Output: src/generated/font.c/.h (linked into the mission segment, 25): per
character an even advance (odd widths get a blank column: the MSX writes
VRAM a byte, two pixels, at a time), the offset of its 1-bit rows, and the
message strings."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'reference_assets/original_files/Wings_of_Fury/newarmyfont'
EXE = ROOT / 'reference_assets/original_files/Wings_of_Fury/wings'
SPACE = 6      # the ticker's space (the font gives it no width)
INK = 11       # mission palette white (7, 7, 7)
MESSAGES = {   # executable strings, NUL-terminated (docs/research/amiga-island-combat.md)
    'g_MessageCleared': b'All enemy forces on island have been destroyed',
    'g_MessageMission': b'Good work ! You are ordered',
    'g_MessagePromotion': b'Congratulations! You have completed',
}


def glyphs():
    d = FONT.read_bytes()
    height, first, last = int.from_bytes(d[0:2], 'big'), d[2], d[3]
    widths = {c: d[4 + c - first] for c in range(first, last + 1)}
    out, p = {}, 4 + (last - first + 1) + 1   # bitmaps follow the widths and a pad byte
    p = 100
    for c in range(first + 1, last + 1):
        bpr = 2 if widths[c] <= 16 else 4
        rows = [int.from_bytes(d[p + r * bpr:p + (r + 1) * bpr], 'big') for r in range(height)]
        out[c] = (widths[c], [[(row >> (bpr * 8 - 1 - x)) & 1 for x in range(widths[c])] for row in rows])
        p += height * bpr
    if p != len(d): raise ValueError('font layout changed')
    out[first] = (SPACE, [[0] * SPACE for _ in range(height)])
    return height, first, last, out


def strings():
    blob = EXE.read_bytes()
    result = {}
    for name, start in MESSAGES.items():
        i = blob.find(start)
        if i < 0 or blob.find(start, i + 1) >= 0: raise ValueError(f'{name}: not found once')
        result[name] = blob[i:blob.index(b'\0', i)]
    return result


def artifacts():
    height, first, last, font = glyphs()
    data, offsets, advance = bytearray(), [], []
    for c in range(first, last + 1):
        width, rows = font[c]
        cell = (width + 1) & ~1
        offsets.append(len(data))
        advance.append(cell)
        for row in rows:
            bits = row + [0] * (cell - width)
            for b in range(0, cell, 8):
                byte = 0
                for x in range(8):
                    if b + x < cell and bits[b + x]: byte |= 0x80 >> x
                data.append(byte)
    msgs = strings()
    def arr(ctype, name, values, per=16):
        body = ',\n'.join('    ' + ', '.join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per))
        return f'const {ctype} {name}[{len(values)}] = {{\n{body}\n}};\n'
    h = f'''/* Generated by tools/convert_font.py; do not edit. */
#pragma once
/* The original's ticker font (newarmyfont), 1 bit per pixel: character c
 * (FONT_FIRST..FONT_LAST) is g_FontAdvance[c - FONT_FIRST] pixels wide
 * (even), its FONT_HEIGHT rows of (advance + 7) / 8 bytes at
 * g_FontBits + g_FontOffset[c - FONT_FIRST]. In segment 25 (mission). */
#define FONT_HEIGHT {height}
#define FONT_FIRST {first}
#define FONT_LAST {last}
#define FONT_INK {INK}
extern const unsigned char g_FontAdvance[{len(advance)}];
extern const unsigned short g_FontOffset[{len(offsets)}];
extern const unsigned char g_FontBits[{len(data)}];
/* The executable's messages: "{msgs['g_MessageCleared'].decode()}" (with
 * the bonus for %ld) and "{msgs['g_MessageMission'].decode()}". */
extern const char g_MessageCleared[{len(msgs['g_MessageCleared']) + 1}];
extern const char g_MessageMission[{len(msgs['g_MessageMission']) + 1}];
extern const char g_MessagePromotion[{len(msgs['g_MessagePromotion']) + 1}];
'''
    c = ('/* Generated by tools/convert_font.py; do not edit. */\n#include "font.h"\n'
         '#include "../msx/banking.h"\nWINGS_CODE_SEGMENT(WINGS_SEGMENT_MISSION)\n')
    c += arr('unsigned char', 'g_FontAdvance', advance)
    c += arr('unsigned short', 'g_FontOffset', offsets)
    c += arr('unsigned char', 'g_FontBits', list(data))
    for name, text in msgs.items():
        esc = text.decode('ascii').replace('\\\\', '\\\\\\\\').replace('"', '\\\\"')
        c += f'const char {name}[{len(text) + 1}] = "{esc}";\n'
    return {ROOT / 'src/generated/font.h': h.encode(), ROOT / 'src/generated/font.c': c.encode()}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, data in artifacts().items():
        if args.check:
            if path.read_bytes() != data: parser.error(f'stale: {path}')
        else:
            path.write_bytes(data)
    print('font verified' if args.check else 'font and messages generated')


if __name__ == '__main__':
    main()
