"""Preserve the original elevator platform, composited over its decoded shaft."""
import argparse
import hashlib
from io import BytesIO
import json
from pathlib import Path
from PIL import Image
from convert_hellcat import pack_pixels
from decode_mission import ROOT, SOURCE
from decode_shapes import decode_record
from unpack_shapes import read_ppkc, unpack_rpck


def artifacts():
    records={n:r for n,_,r in read_ppkc(unpack_rpck((SOURCE/'shapes/world.shp').read_bytes()))}
    raw=records['elev'];pixels,meta=decode_record(raw,plane_constants=True)
    if (meta['width'],meta['height'],meta['origin_candidate'])!=(64,13,[28,-1]):
        raise ValueError('original elevator geometry changed')
    mission=json.loads((ROOT/'assets_src/missions/a-map.json').read_text())
    markers=[c['x'] for c in mission['cells'] if c['shape_id']==37]
    if markers!=[7000]:raise ValueError('elevator marker changed')
    mapping=json.loads((ROOT/'assets_msx/terrain/manifest.json').read_text())['source_to_msx_index']
    scene=(ROOT/'assets_msx/mission_a/scene.indices').read_bytes()
    width=json.loads((ROOT/'assets_msx/mission_a/manifest.json').read_text())['width']
    # Page 1 has only wave frames 8..11 at X=48..143. X=144..239,
    # Y=468..509 is free, above the sky-only wrap rows and beside plane backups.
    background_slots=[(144,468)]
    platform_slots=[(208,468+7*i) for i in range(4)]
    backdrop=bytes(scene[(152+y)*width+7004+x] for y in range(40) for x in range(64))
    platform=bytes(mapping[str(v)] if v else 0 for v in pixels)
    tiles=bytearray(backdrop)
    for row in (0,7):
        for col in (0,32):
            tiles.extend(platform[(row+y)*64+col+x] if row+y<13 else 0 for y in range(7) for x in range(32))
    slots=background_slots+platform_slots
    code='/* Generated by tools/convert_elevator.py; do not edit. */\n#pragma once\n'
    code+='const unsigned char g_ElevatorX[5] = {'+','.join(str(x) for x,y in slots)+'};\n'
    code+='const unsigned short g_ElevatorY[5] = {'+','.join(str(y) for x,y in slots)+'};\n'
    manifest=dict(source='world.shp:elev',sha256=hashlib.sha256(raw).hexdigest(),**meta,
        background_slots=background_slots,platform_slots=platform_slots,marker_x=7000,plane_start_x=7032,world_left=7004,deck_row=129,shaft_bottom=145,
        depth=32,pixel_ticks=18,background_tile_bytes=1280,platform_tile_bytes=112,
        geometry='marker + 32 gives player/platform anchor; source X origin 28; deck/shaft from decoded mcar and supplied captures',
        timing='MSX adaptation: 32 pixels at 18 simulation ticks/pixel; six-VBlank presentation; original timing not recovered')
    folder=ROOT/'assets_msx/elevator'
    files={ROOT/'src/generated/elevator.h':code.encode(),folder/'bank_15.bin':pack_pixels(tiles),folder/'backdrop.indices':backdrop,folder/'platform.indices':platform,folder/'manifest.json':(json.dumps(manifest,indent=2)+'\n').encode(),
           ROOT/'assets_src/ship/elevator.indices':pixels}
    image=Image.frombytes('P',(64,40),backdrop);palette=(ROOT/'assets_msx/mission_a/palette.bin').read_bytes()
    image.putpalette(bytes(v*255//7 for i in range(16) for v in (palette[i*2]>>4,palette[i*2+1],palette[i*2]&7))+bytes(720))
    out=BytesIO();image.save(out,format='PNG');files[folder/'frames.png']=out.getvalue()
    return files

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,data in artifacts().items():
        if args.check:
            if not path.exists() or path.read_bytes()!=data:parser.error(f'stale elevator artifact: {path}')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
