"""Extract the original combined carrier flag/radar frames for VRAM playback."""
import argparse
import hashlib
import json
from io import BytesIO
from pathlib import Path
from PIL import Image
from convert_dashboard import atlas_slots, rle
from convert_hellcat import pack_pixels, c_array
from decode_mission import ROOT, SOURCE
from decode_shapes import decode_record
from unpack_shapes import read_ppkc, unpack_rpck


def artifacts():
    _,_,slots,_=atlas_slots(27,reserve_water=True,reserve_ship=True)
    records={n:r for n,_,r in read_ppkc(unpack_rpck((SOURCE/'shapes/world.shp').read_bytes()))}
    mapping=json.loads((ROOT/'assets_msx/terrain/manifest.json').read_text())['source_to_msx_index']
    frames=[]; raw_pixels=bytearray(); pixels=bytearray()
    for index in range(4):
        name='flg'+str(index+3);raw=records[name]
        source,meta=decode_record(raw,plane_constants=True)
        if (meta['width'],meta['height'],meta['origin_candidate'])!=(32,42,[6,115]):
            raise ValueError('carrier overlay geometry changed')
        if 0 in source:raise ValueError('carrier overlay must replace its full background')
        converted=bytes(mapping[str(v)] for v in source)
        frames.append(dict(name=name,parts=slots[index*6:index*6+6],sha256=hashlib.sha256(raw).hexdigest(),**meta))
        raw_pixels.extend(source);pixels.extend(converted)
    code='/* Generated by tools/convert_ship.py; do not edit. */\n#pragma once\n'
    chunks=b''.join(bytes(pixels[f*1344+(row+y)*32+col+x] for y in range(14) for x in range(16))
                    for f in range(4) for row in range(0,42,14) for col in (0,16))
    encoded=rle(pack_pixels(chunks));code+=c_array('g_ShipRLE',encoded,f'[{len(encoded)}]')
    code+='const unsigned char g_ShipX[24] = {'+','.join(str(x) for x,y in slots)+'};\n'
    code+='const unsigned short g_ShipY[24] = {'+','.join(str(y) for x,y in slots)+'};\n'
    manifest=dict(frames=frames,world_left=6592,world_right=7368,overlay_x=6906,overlay_y=46,
                  heave=[0,1,2,1],heave_step_ticks=45,flag_step_ticks=30,
                  timing='MSX adaptation on the 150 Hz simulation clock; original combined artwork retained')
    files={ROOT/'src/generated/ship.h':code.encode(),ROOT/'assets_src/ship/frames.indices':bytes(raw_pixels),
           ROOT/'assets_msx/ship/frames.indices':bytes(pixels),
           ROOT/'assets_msx/ship/manifest.json':(json.dumps(manifest,indent=2)+'\n').encode()}
    image=Image.frombytes('P',(32,168),bytes(pixels));palette=(ROOT/'assets_msx/mission_a/palette.bin').read_bytes()
    image.putpalette(bytes(v*255//7 for i in range(16) for v in (palette[i*2]>>4,palette[i*2+1],palette[i*2]&7))+bytes(720))
    output=BytesIO();image.save(output,format='PNG');files[ROOT/'assets_msx/ship/frames.png']=output.getvalue()
    return files

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,data in artifacts().items():
        if args.check:
            if not path.exists() or path.read_bytes()!=data:parser.error(f'stale ship artifact: {path}')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
