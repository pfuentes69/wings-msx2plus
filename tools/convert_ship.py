"""Extract the original combined carrier flag/radar frames for VRAM playback."""
import argparse
import hashlib
import json
from io import BytesIO
from pathlib import Path
from PIL import Image
from convert_dashboard import atlas_slots, rle
from convert_hellcat import pack_pixels, c_array
from decode_mission import ROOT, SOURCE
from decode_shapes import decode_record
from unpack_shapes import read_ppkc, unpack_rpck


def artifacts():
    _,_,slots,_,_,crew_slots,_=atlas_slots(27,reserve_water=True,reserve_ship=True,reserve_combat=True,reserve_crew=True)
    records={n:r for n,_,r in read_ppkc(unpack_rpck((SOURCE/'shapes/world.shp').read_bytes()))}
    mapping=json.loads((ROOT/'assets_msx/terrain/manifest.json').read_text())['source_to_msx_index']
    frames=[]; raw_pixels=bytearray(); pixels=bytearray()
    for index in range(4):
        name='flg'+str(index+3);raw=records[name]
        source,meta=decode_record(raw,plane_constants=True)
        if (meta['width'],meta['height'],meta['origin_candidate'])!=(32,42,[6,115]):
            raise ValueError('carrier overlay geometry changed')
        if 0 in source:raise ValueError('carrier overlay must replace its full background')
        converted=bytes(mapping[str(v)] for v in source)
        frames.append(dict(name=name,parts=slots[index*6:index*6+6],sha256=hashlib.sha256(raw).hexdigest(),**meta))
        raw_pixels.extend(source);pixels.extend(converted)
    code='/* Generated by tools/convert_ship.py; do not edit. */\n#pragma once\n'
    chunks=b''.join(bytes(pixels[f*1344+(row+y)*32+col+x] for y in range(14) for x in range(16))
                    for f in range(4) for row in range(0,42,14) for col in (0,16))
    code+='#define SHIP_PIXELS_OFFSET 2618\n#define CREW_PIECES 34\n#define CREW_IDLE_PIECE 32\n'
    code+='const unsigned char g_ShipX[24] = {'+','.join(str(x) for x,y in slots)+'};\n'
    code+='const unsigned short g_ShipY[24] = {'+','.join(str(y) for x,y in slots)+'};\n'
    # Special fgyx markers are not ordinary static draw cells. The original
    # renderer overlays fgy0..7 and fgy8..f at each marker using their origins.
    mission=json.loads((ROOT/'assets_src/missions/a-map.json').read_text())
    scene=json.loads((ROOT/'assets_src/missions/a-scene.json').read_text())
    anchors=[cell['x'] for cell in mission['cells'] if cell['shape_id']==159]
    if anchors != [6968,7344]: raise ValueError('signalman markers changed')
    original_scene=(ROOT/'assets_src/missions/a.indices').read_bytes()
    crew=[];composites=bytearray();original_crew=bytearray()
    for i in range(16):
        name=f'fgy{i:x}';raw=records[name];pixels0,meta=decode_record(raw,plane_constants=True)
        original_crew.extend(pixels0)
        crew.append(dict(name=name,sha256=hashlib.sha256(raw).hexdigest(),**meta))
    poses=[(anchor,(1,phase+8)) for anchor in anchors for phase in range(8)]
    poses.append((anchors[0],(0,8))) # Elevator signalman: both arms down.
    for anchor,arms in poses:
        # 22-pixel byte-aligned rectangle at anchor-10; all opaque source
        # crew pixels fit, and the decoded scenery remains behind them.
        patch=bytearray(original_scene[(116+40+y)*scene['width']+anchor-10+x]
                        for y in range(14) for x in range(22))
        for i in arms:
            pixels0,meta=decode_record(records[f'fgy{i:x}'],plane_constants=True)
            ox,oy=meta['origin_candidate']
            for y in range(meta['height']):
                for x in range(meta['width']):
                    value=pixels0[y*meta['width']+x]
                    if value:
                        dx=x-ox+10;dy=161-oy+y-116
                        if not (0<=dx<22 and 0<=dy<14):raise ValueError('crew crop clips original pixels')
                        patch[dy*22+dx]=value
        composites.extend(mapping[str(v)] for v in patch)
    code+='const unsigned char g_CrewX[34] = {'+','.join(str(x) for x,y in crew_slots)+'};\n'
    code+='const unsigned short g_CrewY[34] = {'+','.join(str(y) for x,y in crew_slots)+'};\n'
    manifest=dict(crew_pointing_arms=dict(fixed_left=1,right_cycle=list(range(8,16))),crew_idle_arms=[0,8],crew_idle_frame=16,crew_frame_count=17,crew_records=crew,crew_anchors=anchors,crew_slots=crew_slots,crew_width=22,crew_height=14,crew_piece_height=7,crew_top=116,crew_step_ticks=15,
                  crew_timing='MSX adaptation: left arm fixed horizontally; right arm cycles at 10 Hz. Elevator signalman has both arms down off deck; end signalman always points.',
                  crew_crop='anchor-10; opaque decoded scenery plus transparent original figures',
                  frames=frames,world_left=6592,world_right=7368,overlay_x=6906,overlay_y=46,
                  heave=[0,1,2,1],heave_step_ticks=45,flag_step_ticks=30,
                  timing='MSX adaptation on the 150 Hz simulation clock; original combined artwork retained')
    files={ROOT/'assets_msx/ship/bank_13.bin':pack_pixels(composites)+pack_pixels(chunks),
           ROOT/'assets_msx/ship/crew.indices':bytes(composites),
           ROOT/'assets_src/ship/crew.indices':bytes(original_crew),
           ROOT/'src/generated/ship.h':code.encode(),ROOT/'assets_src/ship/frames.indices':bytes(raw_pixels),
           ROOT/'assets_msx/ship/frames.indices':bytes(pixels),
           ROOT/'assets_msx/ship/manifest.json':(json.dumps(manifest,indent=2)+'\n').encode()}
    image=Image.frombytes('P',(32,168),bytes(pixels));palette=(ROOT/'assets_msx/mission_a/palette.bin').read_bytes()
    image.putpalette(bytes(v*255//7 for i in range(16) for v in (palette[i*2]>>4,palette[i*2+1],palette[i*2]&7))+bytes(720))
    output=BytesIO();image.save(output,format='PNG');files[ROOT/'assets_msx/ship/frames.png']=output.getvalue()
    image=Image.frombytes('P',(22,14*17),bytes(composites));image.putpalette(bytes(v*255//7 for i in range(16) for v in (palette[i*2]>>4,palette[i*2+1],palette[i*2]&7))+bytes(720))
    output=BytesIO();image.save(output,format='PNG');files[ROOT/'assets_msx/ship/crew.png']=output.getvalue()
    return files

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    for path,data in artifacts().items():
        if args.check:
            if not path.exists() or path.read_bytes()!=data:parser.error(f'stale ship artifact: {path}')
        else:path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data)
