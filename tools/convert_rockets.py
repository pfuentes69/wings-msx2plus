"""Copy the rocket's trigonometry tables out of the Amiga executable into
src/generated/rocket_tables.h (docs/rockets.md).

The tables sit in the DATA hunk, addressed from A4 (A4 - n is data offset
0x7ffe - n):

- sine -$6692: 257 words, a quarter wave in Q15 (0x5108 / 0x5104 read it
  for sine and cosine, 1024 steps a turn);
- tangent -$6892: words in Q8 by angle (0x514c; 1024 steps a turn). The
  rocket's aim reads entries up to 84, so the first 128 are kept;
- arctangent -$5810: 257 bytes, atan(i / 256) in 1024 steps a turn (0x5ca6).

The code that reads them is checked byte for byte first."""
import argparse
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]
EXECUTABLE = ROOT / 'reference_assets/original_files/Wings_of_Fury/wings'
OUTPUT = ROOT / 'src/generated/rocket_tables.h'
# CODE-hunk offset: the instructions that must be there.
EVIDENCE = {
    0x08fe: '48e72810382ca406e24431440026316ca41600283004',   # launch: angle -$5bfa / 2, airspeed
    0x099a: '48e70f102648382b0026e2444a446a0000be',           # aim: half the angle, downward only
    0x5108: '2f08c07c03ff41ec996eb07c0100',                   # sine table -$6692
    0x514c: '48e7408032006a0000044440c07c00ff41ec976e',       # tangent table -$6892
    0x5ce6: '41eca7f01030100041eca7d0',                       # arctangent table -$5810
}


def hunks(data):
    """CODE and DATA hunks of an Amiga HUNK executable, in order."""
    pos = 0
    def word():
        nonlocal pos
        value = struct.unpack('>I', data[pos:pos + 4])[0]
        pos += 4
        return value
    if word() != 0x3f3:
        raise ValueError('not an Amiga HUNK executable')
    while word():
        pass
    word(); first, last = word(), word()
    for _ in range(last - first + 1):
        word()
    result = []
    while pos < len(data):
        kind = word() & 0x3fffffff
        if kind in (0x3e9, 0x3ea):
            n = word()
            result.append((kind, data[pos:pos + 4 * n]))
            pos += 4 * n
        elif kind == 0x3eb:
            word()
        elif kind == 0x3ec:
            while True:
                n = word()
                if not n:
                    break
                word(); pos += 4 * n
        elif kind == 0x3f2:
            continue
        else:
            break
    return result


def tables():
    parts = hunks(EXECUTABLE.read_bytes())
    code = next(h for k, h in parts if k == 0x3e9)
    data = next(h for k, h in parts if k == 0x3ea)
    for offset, expected in EVIDENCE.items():
        expected = bytes.fromhex(expected.replace(' ', ''))
        if code[offset:offset + len(expected)] != expected:
            raise ValueError(f'executable differs at code offset {offset:#x}')
    def at(n, size):
        return data[0x7ffe - n:0x7ffe - n + size]
    sine = struct.unpack('>257h', at(0x6692, 514))
    tangent = struct.unpack('>128H', at(0x6892, 256))
    arctangent = at(0x5810, 257)
    if sine[0] != 0 or sine[256] != 32767 or tangent[128 - 1] > tangent[127] or arctangent[256] != 128:
        raise ValueError('unexpected table contents')
    return sine, tangent, arctangent


def header():
    sine, tangent, arctangent = tables()
    def rows(values):
        values = [str(v) for v in values]
        return ''.join('    ' + ', '.join(values[i:i + 16]) + ',\n' for i in range(0, len(values), 16))
    return ('/* Generated by tools/convert_rockets.py; do not edit.\n'
            ' * The Amiga executable\'s trigonometry (DATA -$6692, -$6892, -$5810), 1024\n'
            ' * steps a turn. Include only from core/combat.c (banked). */\n#pragma once\n'
            'static const int16_t s_Sine[257] = {\n' + rows(sine) + '};\n'
            'static const uint16_t s_Tangent[128] = {\n' + rows(tangent) + '};\n'
            'static const uint8_t s_Arctangent[257] = {\n' + rows(arctangent) + '};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = header()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            parser.error(f'missing or stale {OUTPUT}')
        return
    OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
